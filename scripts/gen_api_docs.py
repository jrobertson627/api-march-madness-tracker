"""Write docs/api.md from the response schemas and invented sample data.

    python scripts/gen_api_docs.py

Field tables come from api/schemas.py, so the docs cannot drift from what the tests validate. The example responses
use the invented sample snapshot in api/sample.py. The numbers in them are made up.
"""

import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from api.app import create_app  # noqa: E402
from api.config import Config  # noqa: E402
from api.sample import sample_bundle  # noqa: E402
from api.schemas import SCHEMAS  # noqa: E402
from api.store import FileStore  # noqa: E402


def type_text(s: dict) -> str:
    t = s.get("type") or ("one of " + "/".join(type_text(x) for x in s.get("oneOf", [])) if "oneOf" in s else "")
    if "enum" in s:
        return " or ".join(f"`{e}`" for e in s["enum"])
    if isinstance(t, list):
        return " or ".join(t)
    if t == "array":
        return f"list of {type_text(s['items'])}" if "items" in s else "list"
    return t or "any"


def rows(schema: dict, prefix: str = "") -> list[tuple]:
    out = []
    required = set(schema.get("required", []))
    for name, sub in schema.get("properties", {}).items():
        out.append((f"{prefix}{name}", type_text(sub), "yes" if name in required else "no"))
        node = sub["items"] if sub.get("type") == "array" and isinstance(sub.get("items"), dict) else sub
        if node.get("type") == "object" and "properties" in node:
            out += rows(node, f"{prefix}{name}.")
        elif sub.get("type") == "array" and node.get("type") == "object" and "properties" in node:
            out += rows(node, f"{prefix}{name}[].")
    return out


def table(schema: dict) -> str:
    lines = ["| field | type | always present |", "|---|---|---|"]
    lines += [f"| `{n}` | {t} | {r} |" for n, t, r in rows(schema)]
    return "\n".join(lines)


def main() -> None:
    with tempfile.TemporaryDirectory() as d:
        store = FileStore(d)
        store.write_snapshot(sample_bundle(2030, "example-model"), activate=True)
        client = create_app(Config(), store=store).test_client()
        mu = client.get("/v1/predict/matchup?team_a=e1&team_b=w1&season=2030").get_json()
        br = client.get("/v1/bracket/2030").get_json()
        br_short = dict(br, field=br["field"][:2], picks={k: v[:2] for k, v in br["picks"].items()}, first_round=br["first_round"][:2])
        err = client.get("/v1/predict/matchup?team_a=e1&team_b=nobody&season=2030").get_json()
        odds = client.post("/v1/bracket/2030/odds", json={"results": [{"team_a": "s1", "team_b": "s16", "winner": "s16"}]}).get_json()
        odds_short = dict(odds, field=odds["field"][:2], picks={k: v[:1] for k, v in odds["picks"].items()}, first_round=odds["first_round"][:1])

    def j(x):
        return "```json\n" + json.dumps(x, indent=2)[:2600] + "\n```"

    md = f"""# API reference

Generated by `scripts/gen_api_docs.py` from `api/schemas.py`. The examples use invented sample data: the numbers are made up
and are only there to show the shape of each response.

## What the numbers mean

- **Win probabilities** come from a boosted-trees model for a game on a **neutral court**. On the tournament games it was tested on, it is about as good as betting lines and a simple efficiency model, not better.
- **Every answer names its model and snapshot.** `snapshot.in_sample` is true when the model was trained on that season, in which case the probability is not a fair test of the model. For a season, the API prefers a model that did not train on it.
- **Projected scores** are for a 40-minute game (overtime is not included).
- **Factors** show how far the win probability moves when one group of inputs is set to zero. They are descriptions of what the model does, not causes. They do not add up exactly; `interaction` is what is left over.
- **Odds** in `/v1/bracket` assume independent games with the ratings frozen at Selection Sunday.

## Conventions

- Team ids are school slugs such as `michigan-state` (the same ids as `/teams`).
- Errors always look like `{{"error": {{"code", "message", "details"}}}}`. `400` is a bad parameter, `404` an unknown team, season or snapshot, `413` a body that is too large, `422` results that do not fit the bracket, `503` the prediction store is unavailable.
- GET responses carry an `ETag` and `Cache-Control`. Send `If-None-Match` to get `304` when nothing changed.
- Snapshots never change once published, so a response for a past season is the same tomorrow.
- CORS allows only the origins in `CORS_ORIGINS`.

## GET /health

Always `200` while the web service is up. `status` is `degraded` when the prediction store cannot be reached.

{table(SCHEMAS['health'])}

## GET /v1/models, GET /v1/seasons

Model versions (with held-out metrics and the active flag), and the seasons that have published snapshots.

{table(SCHEMAS['models'])}

{table(SCHEMAS['seasons'])}

## GET /v1/predict/matchup

Query: `team_a`, `team_b` (slugs), `season`; optional `model` (a model id) and `as_of` (YYYY-MM-DD).

{table(SCHEMAS['matchup'])}

Example (invented numbers):

{j(mu)}

## GET /v1/bracket/{{season}}

Query: optional `scoring` (six comma-separated point values, round 1 to the championship; default `10,20,40,80,160,320`) and `model`.
`picks` has three brackets: `best_expected_points` (the consistent bracket with the most expected points), `model_favorite` and `seed_chalk`.
`first_round[].flagged` is true when the model gives the underdog at least 50% (`model_picks_upset`) or at least 15 points above the
historical rate for that seed pairing (`model_above_history`). In the backtest only the first of those flags beat the base rate.

{table(SCHEMAS['bracket'])}

Example, trimmed to the first rows (invented numbers):

{j(br_short)}

## GET /v1/bracket/{{season}}/matchups?round=1

The round-of-64 games with the model's probabilities. Only round 1 is available before results are known.

{table(SCHEMAS['round_matchups'])}

## POST /v1/bracket/{{season}}/odds

What-if mode. Body: `{{"results": [{{"team_a": ..., "team_b": ..., "winner": ...}}], "scoring": [..six numbers..], "model": ...}}`.
Games already played keep their real winners and the rest is recalculated. A result that cannot happen given the others returns `422`.
The response has the same shape as `GET /v1/bracket/{{season}}` and is not cached.

Example, locking one result (invented numbers, trimmed):

{j(odds_short)}

## Errors

{table(SCHEMAS['error'])}

Example:

{j(err)}
"""
    out = ROOT / "docs" / "api.md"
    out.write_text(md, encoding="utf-8")
    print(f"wrote {out} ({len(md):,} characters)")


if __name__ == "__main__":
    main()
